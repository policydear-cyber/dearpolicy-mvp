/**
 * Conversational RAG, Prompt 2 demonstration (npm run rag2:loop-demo).
 *
 * PGlite with the synthetic household (scripts/fixtures/rag2-loop/household.ts), DEARPOLICY_RAG_LOOP=1, and the
 * TEST-ONLY scripted model (its script is scripts/fixtures/rag2-loop/conversations.ts). Every turn is posted to the
 * real chat route; for each turn this prints the household's message, the tool calls the model made, the evidence
 * the answer rests on (policy, page, row / column, passage) and the VISIBLE reply as saved after the save-time gate.
 * The transcript is written to DEMO-TRANSCRIPT.md (or the path given as the first argument).
 *
 *  (a) an ordinary policy question with a figure
 *  (b) "my son" with two sons -> one question -> the chosen child's own column
 *  (c) injury fact-finding for the child's fracture, one question at a time
 *  (d) an interruption mid-claim ("by the way what's my deductible?") answered, then the pending question re-asked
 *  (e) a correction ("actually it was 3 nights, not 2") updating the facts and withdrawing what was derived
 *  (f) the grounded final answer: cited printed limits and labelled indicative estimates
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { setEnv, startHarness } from "./fixtures/rag2-loop/harness";
import { claimConversation, CLAIM_MESSAGES, POLICY_MESSAGE, POLICY_QUESTION } from "./fixtures/rag2-loop/conversations";
import { DOCS, M } from "./fixtures/rag2-loop/household";

setEnv();
process.env.DEARPOLICY_RAG_LOOP = "1";

const LABELS: Record<string, string> = { "0:0": "(a) ordinary policy question with a figure", "1:0": "(b) ambiguous person: \"my son\" with two sons", "1:1": "(b) the household chooses; answer from the child's column", "1:2": "(c) injury fact-finding: first question", "1:3": "(c) fact-finding: next question (one at a time; a re-ask of a known fact is refused)", "1:4": "(d) interruption mid-claim, then the pending question re-asked", "1:5": "(f) claim answer once every input is known (2 nights)", "1:6": "(e)+(f) correction: 3 nights, not 2 -- facts updated, derived estimate withdrawn, grounded final answer" };

async function main() {
  const h = await startHarness();
  const { installLoopModel } = await import("@/lib/rag2/loop/model");
  const { ScriptedLoopModel } = await import("@/lib/rag2/loop/scripted-model");
  const product = (id: string) => DOCS.find((d) => d.id === id)?.product ?? id;
  const md: string[] = ["# DearPolicy conversation loop -- demo transcript", "", "Generated by `npm run rag2:loop-demo` (PGlite, synthetic household, DEARPOLICY_RAG_LOOP=1, scripted test model). Every turn went through the real chat route (`app/api/chat/route.ts` -> `lib/chat/workflow.ts` flagged hook -> `lib/rag2/loop`), and the reply shown is the one saved after the save-time gate (`chat_messages.answer_json`).", ""];
  const out = (s = "") => { console.log(s); md.push(s); };
  const conversations = [{ title: "Conversation 1", script: POLICY_QUESTION, messages: [POLICY_MESSAGE] }, { title: "Conversation 2", script: claimConversation(), messages: CLAIM_MESSAGES }];
  for (const [ci, c] of conversations.entries()) {
    installLoopModel(new ScriptedLoopModel(c.script));
    out(`## ${c.title}`); out();
    let conv: { id?: string; rev?: number } = {};
    for (const [ti, message] of c.messages.entries()) {
      const answer = await h.send(message, conv);
      conv = { id: answer.conversationId, rev: answer.conversationRevision };
      const saved = await h.savedAnswer(conv.id!);
      const loop = saved.state.ragLoop;
      const trace = loop.turns[loop.turns.length - 1];
      out(`### Turn ${ti + 1} — ${LABELS[`${ci}:${ti}`] ?? ""}`); out();
      out(`**Household:** ${message}`); out();
      out(`**Model:** \`${trace.modelId}\` (${trace.modelKind}) · steps ${trace.steps} · tokens in/out ${trace.usage.input}/${trace.usage.output} · ${trace.latencyMs} ms · outcome \`${trace.outcome}\``); out();
      out("**Tool calls:**"); out();
      for (const t of trace.toolCalls) out(`- \`${t.name}\`(${JSON.stringify(t.args).replace(/"[0-9a-f]{8}-[0-9a-f-]{27}"/g, (m: string) => { const id = m.slice(1, -1); const who = Object.values(M).find((p: any) => p.id === id) as any; return who ? `"<${who.pref ?? who.name}>"` : DOCS.some((d) => d.id === id) ? `"<${product(id)}>"` : m; }).slice(0, 400)}) → ${t.ok ? "ok" : "REFUSED: " + t.error}${t.summary ? " " + t.summary : ""}${t.evidenceIds.length ? ` [evidence ${t.evidenceIds.slice(0, 8).join(", ")}${t.evidenceIds.length > 8 ? ", …" : ""}]` : ""}`);
      out();
      out("**Evidence the reply rests on:**"); out();
      if (!trace.evidenceChosen.length) out("- (none: no statement about cover or figures in this reply)");
      const shown = [saved.answer.summary, ...saved.answer.details].join(" ");
      const visibleText = [shown, ...(saved.answer.questions ?? []).map((q: any) => q.text + " " + q.why)].join(" ");
      const excerpt = (text: string) => {
        // A long passage (a whole page) is shown by the lines that print a figure the reply states.
        if (text.length <= 220) return text.replace(/\s+/g, " ");
        const figs = (shown.match(/S\$[\d,]+/g) ?? []);
        const words = new Set((visibleText.toLowerCase().match(/[a-z]{5,}/g) ?? []));
        const byFigure = text.split(/\n/).filter((l) => figs.some((f) => l.includes(f)));
        const byWords = text.split(/\n/).map((l) => ({ l, n: (l.toLowerCase().match(/[a-z]{5,}/g) ?? []).filter((w) => words.has(w)).length })).filter((x) => x.n >= 2).sort((a, b) => b.n - a.n).slice(0, 1).map((x) => x.l);
        const lines = byFigure.length ? byFigure : byWords;
        return (lines.length ? lines.join(" … ") : text.slice(0, 220) + " …").replace(/\s+/g, " ");
      };
      for (const id of trace.evidenceChosen) { const e = loop.evidence[id]; out(`- ${id}: ${product(e.policyId)}, page ${e.passage.onPage}${e.table ? `, row “${e.table.rowLabel}”, column “${e.table.columnHeader}”` : ""} — “${excerpt(e.passage.text)}”`); }
      out();
      if (trace.dropped?.length) { out("**Dropped by the composer:**"); for (const d of trace.dropped) out(`- “${d.sentence}” — ${d.reason}`); out(); }
      out(`**Save-time gate:** ${trace.gate.length ? trace.gate.map((g: any) => `${g.where} ${g.figure}: ${g.reason}`).join("; ") : "every figure verified (nothing removed)"}`); out();
      out("**Visible reply (as saved):**"); out();
      const a = saved.answer;
      out("> " + a.summary);
      for (const d of a.details) out("> " + d);
      for (const q of a.questions ?? []) out(`> **Question:** ${q.text}${q.options?.length ? ` (options: ${q.options.join(" / ")})` : ""} — _why: ${q.why}_`);
      for (const s of a.nextSteps ?? []) out(`> **Next step:** ${s}`);
      if (a.disclaimer) out(`> _${a.disclaimer}_`);
      if (a.citations?.length) out(`> Sources: ${[...new Set(a.citations.map((x: any) => `${x.policyName} p.${x.pageStart}`))].join("; ")}`);
      out();
      if (trace.reasked) { out(`_Pending claim question re-asked after the side answer: “${trace.reasked}”_`); out(); }
      if (trace.corrections?.length) { out(`_Corrections: ${trace.corrections.map((x: any) => `${x.key}: ${x.from} → ${x.to}`).join("; ")}_`); out(); }
    }
    if (ci === 1) {
      const facts = (await h.savedAnswer(conv.id!)).state.ragLoop.claim;
      out("**Claim state at the end:**"); out();
      out("```json"); out(JSON.stringify(facts, null, 2)); out("```"); out();
    }
  }
  out(`Network calls attempted: ${h.networkCalls.length}`);
  const file = path.resolve(process.argv[2] ?? "DEMO-TRANSCRIPT.md");
  await writeFile(file, md.join("\n") + "\n");
  console.log("\ntranscript written to " + file);
  process.exit(0);
}
main().catch((e) => { console.error(e); process.exit(1); });
