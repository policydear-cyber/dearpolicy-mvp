/**
 * Live-model smoke: writes docs/rag-migration/live/EXPECTED.md -- the six conversations' source-grounded expected
 * behaviour, generated from scripts/rag2-live/scenarios.ts (the single source the checker grades against), with every
 * supporting passage checked verbatim against the fixture pages first.
 *   node --import tsx scripts/rag2-live/expected.ts
 */
import fs from "node:fs";
import { doc } from "../fixtures/rag2-live/household";
import { SCENARIOS } from "./scenarios";

const q = (t: string) => "`" + t.replace(/\t/g, " ⇥ ").replace(/`/g, "'") + "`";
const L: string[] = ["# Live-model smoke — expected behaviour", "", "Generated by `node --import tsx scripts/rag2-live/expected.ts` from `scripts/rag2-live/scenarios.ts` (what `scripts/rag2-live/check.ts` grades). Household: synthetic **Lim** (`scripts/fixtures/rag2-live/household.ts`) — Daniel (self, the person typing), Grace (spouse), Kai (son), Mei (daughter). Passages are verbatim from the stored pages (⇥ = a tab in the stored text).", ""];
for (const s of SCENARIOS) {
  L.push(`## ${s.id} — ${s.title}`, "", s.why, "");
  s.turns.forEach((t, i) => {
    const e = t.expect;
    L.push(`**Turn ${i + 1}** — “${t.user}”`, "");
    for (const p of e.passages ?? []) {
      const d = doc(p.doc);
      if (!d.pages[p.page]?.includes(p.text)) throw new Error(`${s.id}: passage not verbatim on ${p.doc} p${p.page}: ${p.text}`);
      const page = d.pages[p.page], at = page.indexOf(p.text);
      const line = page.slice(page.lastIndexOf("\n", at) + 1, page.indexOf("\n", at + p.text.length) < 0 ? undefined : page.indexOf("\n", at + p.text.length)).replace(/ {3,}/g, " ⇥ ");
      const header = /\bS\$/.test(line) && !/^Benefit/.test(line) ? page.split("\n").filter((l) => /^Benefit\b/.test(l)).pop()?.replace(/ {3,}/g, " ⇥ ") : null;
      L.push(`- Supporting passage: ${d.product} (${d.policyNumber}${d.role === "endorsement" ? ", endorsement" : ""}), page ${p.page}: ${q(line)}${header ? ` (table header ${q(header)})` : ""}`);
    }
    if (e.figures?.length) L.push(`- Must show: ${e.figures.join(", ")}`);
    if (e.binding) L.push(`- Figure bound to ${e.binding.member} / ${e.binding.doc}${e.binding.column ? " / column " + e.binding.column : ""} = ${e.binding.value.toLocaleString("en-SG")}`);
    if (e.calculation) { L.push(`- Calculation (${e.calculation.calculator}, ${e.calculation.kind}): ${e.calculation.formula}`); for (const o of e.calculation.operands) L.push(`  - operand ${o.label} = ${o.value} (${o.source}: ${o.from})`); L.push("  - the saved CalculationRecord must recompute (lib/claims/calc-record.ts) to " + e.calculation.result); }
    if (e.asks) L.push(`- Must ask: ${e.asks.about}`);
    if (e.pendingReasked) L.push("- Must put the pending question back after answering the side question");
    if (e.mustNotAsk) L.push(`- Must not ask again: ${e.mustNotAsk.about}`);
    if (e.noQuestion) L.push("- Asks no question");
    if (e.subject) L.push(`- Conversation subject afterwards: ${e.subject}`);
    for (const x of e.says ?? []) L.push(`- Must say: ${x.about}`);
    if (e.noMoney) L.push("- Forbidden: any money figure");
    if (e.noMoneyNear) L.push(`- Forbidden: any money figure in a sentence about /${e.noMoneyNear}/`);
    if (e.onlyPrintedFigures) L.push("- Forbidden: any figure not printed in the household's documents (or the saved calculation's result)");
    for (const f of e.forbidden ?? []) L.push(`- Forbidden: ${f.figure} — ${f.why}${f.unless ? " (allowed only in a sentence that says it was the old / other figure)" : ""}`);
    for (const f of e.factNotRecorded ?? []) L.push(`- Forbidden: recording ${f.key}=${f.value} — ${f.why}`);
    if (e.factRecorded) L.push(`- Must record how it happened in the household's words (“${e.factRecorded.wordsInclude}”)`);
    L.push("");
  });
}
fs.mkdirSync("docs/rag-migration/live", { recursive: true });
fs.writeFileSync("docs/rag-migration/live/EXPECTED.md", L.join("\n"));
console.log("wrote docs/rag-migration/live/EXPECTED.md");
